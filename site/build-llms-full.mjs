// Builds site/atep.dev/llms-full.txt from the Draft 08 specification.
// Usage: node site/build-llms-full.mjs   (no dependencies, Node 18 or later)
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SPEC = "spec/ATEP-Specification-Draft-08.md";
const specPath = path.join(here, "..", SPEC);
const outPath = path.join(here, "atep.dev", "llms-full.txt");

const spec = fs.readFileSync(specPath, "utf8");
const sha = crypto.createHash("sha256").update(spec).digest("hex");
const note = `<!--
llms-full.txt for https://atep.dev

What this is: the complete text of the Autonomy Trust Envelope Protocol (ATEP)
specification, Draft 08 (3 October 2026), as plain Markdown, in one file, so a model
or tool can load the whole protocol in a single fetch.

What it is not: it is not a different document. Everything after the end of this
comment is the unmodified source file "${SPEC}"
(${Buffer.byteLength(spec)} bytes, SHA-256 ${sha}). This file is generated by
site/build-llms-full.mjs; do not edit it by hand.

Status: working draft. Not an Internet-Draft or a standard. Media types, CBOR tags and
COSE labels marked provisional are not registered with IANA. Where the text and the
443 test vectors disagree, the vectors win. Licence of the text: CC BY 4.0,
https://creativecommons.org/licenses/by/4.0/ . Code is Apache-2.0.
Map of the site: https://atep.dev/llms.txt
-->

`;
fs.writeFileSync(outPath, note + spec);
console.log(`wrote ${path.relative(process.cwd(), outPath)} (${Buffer.byteLength(note + spec)} bytes) from ${SPEC}`);
