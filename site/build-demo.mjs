// Generates site/atep.dev/demo/ (served at https://atep.dev/demo/) from the ATEP-R demo in demo/.
//
//   node site/build-demo.mjs           write the files
//   node site/build-demo.mjs --check   fail (exit 1) when the committed copy is stale or has extra files
//
// demo/ stays the single source of truth and is never modified. Only what a browser needs is copied: index.html,
// style.css, src/*.mjs, the built @atep/core glue and wasm, and its third-party notices. selftest.mjs, serve.mjs,
// package.json, README.md and the TypeScript declarations are left out. The output is committed because Heroku
// deploys only site/. No dependencies.
//
// The copy differs from the source in three small, deliberate ways, all so that it runs under the site's strict
// Content-Security-Policy (no inline style, no inline script) and looks like part of atep.dev:
//   1. index.html gets a delimited head block (canonical, social tags, icons) and a footer block with the
//      real-versus-simulated note and links back to atep.dev. There is no top bar: the page opens in its own tab.
//      The demo's data: icon is replaced by the site icons.
//   2. src/ui.mjs: two helpers set style="" attributes with setAttribute, which CSP blocks. The copy assigns
//      element.style.cssText instead (CSSOM is allowed by CSP). Same result, no logic change.
//   3. demo-site.css (new) styles the injected footer.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "..", "demo");
const out = path.join(here, "atep.dev", "demo");
const ORIGIN = "https://atep.dev";
const CANONICAL = `${ORIGIN}/demo/`;
const OG_IMAGE = `${ORIGIN}/assets/og-card.jpg`;
const BEGIN = "<!-- BEGIN atep.dev injected (generated by site/build-demo.mjs, do not edit) -->";
const END = "<!-- END atep.dev injected -->";

const REAL_VS_SIMULATED = "What is real and what is simulated. Real: every key, attestation, revocation list and envelope, every signature, encryption, verification and decryption, including the error codes and steps shown, all done by the reference Rust crate compiled to WebAssembly. Simulated: the map, unit movement, battery values, the scripted timeline, the clock, the moment the controller goes offline, and the certified status of Units 2 and 4, so no real certification is implied. When the controller is offline, units verify each other with the certificates and revocation lists they saved earlier; a revocation published meanwhile cannot reach them until the controller is back. This is an illustration of the robotics profile, not a product.";

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const SITE_CSS = `/* Generated by site/build-demo.mjs. Styles only the atep.dev footer injected into the demo page. */
.atep-site-foot { background: #0d0e11; color: #a9abb3; font: 14px/1.5 system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; padding: 8px 16px; }
.atep-site-foot { border-top: 1px solid #23262c; padding-top: 12px; padding-bottom: 16px; }
.atep-site-foot p { margin: 0 0 6px; max-width: 110ch; }
.atep-site-foot a { color: #5fcaf6; text-underline-offset: 0.18em; }
.atep-site-foot a:hover { color: #e7e5ea; }
.atep-site-foot a:focus-visible { outline: 3px solid #17b5f1; outline-offset: 2px; border-radius: 3px; }
`;

function replaceOnce(text, from, to, what) {
  const i = text.indexOf(from);
  if (i < 0 || text.indexOf(from, i + 1) >= 0) throw new Error(`build-demo: expected exactly one occurrence of ${what} in the demo source; the generator needs updating`);
  return text.slice(0, i) + to + text.slice(i + from.length);
}

function transformHtml(html) {
  const title = /<title>([^<]+)<\/title>/.exec(html)?.[1];
  const desc = /<meta name="description" content="([^"]+)">/.exec(html)?.[1];
  if (!title || !desc) throw new Error("build-demo: demo/index.html has no title or description");
  // The page's own icon is an inline data: URI; the site icons replace it.
  const icon = /<link rel="icon" href="data:[^"]*">\n/.exec(html);
  if (!icon) throw new Error("build-demo: demo/index.html has no data: icon link to replace");
  html = replaceOnce(html, icon[0], "", "the data: icon link");
  const ogTitle = "ATEP-R live simulator";
  const head = `${BEGIN}
<link rel="canonical" href="${CANONICAL}">
<link rel="stylesheet" href="demo-site.css">
<meta name="theme-color" content="#0c0d0f">
<link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">
<link rel="icon" href="/assets/favicon-32.png" type="image/png" sizes="32x32">
<link rel="apple-touch-icon" href="/assets/apple-touch-icon.png">
<meta property="og:type" content="website">
<meta property="og:site_name" content="ATEP">
<meta property="og:title" content="${ogTitle}">
<meta property="og:description" content="${desc}">
<meta property="og:url" content="${CANONICAL}">
<meta property="og:image" content="${OG_IMAGE}">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="ATEP">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${ogTitle}">
<meta name="twitter:description" content="${desc}">
<meta name="twitter:image" content="${OG_IMAGE}">
${END}
`;
  html = replaceOnce(html, "</head>", head + "</head>", "</head>");
  const foot = `${BEGIN}
<div class="atep-site-foot">
  <p>${esc(REAL_VS_SIMULATED)}</p>
  <p><a href="/">atep.dev</a> | <a href="/about.html">About</a> | <a href="/specification.html">Specification</a> | <a href="https://github.com/atepdev/atep">Source</a> | <a href="vendor/atep-core/THIRD-PARTY-NOTICES.md">Third-party notices</a></p>
</div>
${END}
`;
  html = replaceOnce(html, "<noscript>", foot + "<noscript>", "<noscript>");
  return html;
}

// CSP blocks setAttribute("style", ...) (style-src has no 'unsafe-inline'); assigning style.cssText is CSSOM and allowed.
function transformUi(js) {
  js = replaceOnce(js, '    else e.setAttribute(k, v === true ? "" : v);', '    else if (k === "style") e.style.cssText = v;\n    else e.setAttribute(k, v === true ? "" : v);', "the h() setAttribute line");
  js = replaceOnce(js, "  for (const [k, v] of Object.entries(attrs)) if (v != null) e.setAttribute(k, v);\n  for (const c of kids.flat()) if (c != null) e.append(c.nodeType ? c : document.createTextNode(String(c)));\n  return e;\n}\nconst kb",
    '  for (const [k, v] of Object.entries(attrs)) if (v != null) { if (k === "style") e.style.cssText = v; else e.setAttribute(k, v); }\n  for (const c of kids.flat()) if (c != null) e.append(c.nodeType ? c : document.createTextNode(String(c)));\n  return e;\n}\nconst kb', "the s() setAttribute line");
  return "// atep.dev copy: h() and s() assign style.cssText instead of setAttribute(\"style\") so the page runs under CSP (generated by site/build-demo.mjs).\n" + js;
}

// Everything the browser needs, as a map from published path to bytes.
export function buildFiles() {
  const read = (rel) => fs.readFileSync(path.join(src, rel));
  const files = new Map();
  files.set("index.html", Buffer.from(transformHtml(read("index.html").toString("utf8"))));
  files.set("style.css", read("style.css"));
  files.set("demo-site.css", Buffer.from(SITE_CSS));
  for (const f of fs.readdirSync(path.join(src, "src")).filter((n) => n.endsWith(".mjs")).sort()) {
    files.set(`src/${f}`, f === "ui.mjs" ? Buffer.from(transformUi(read("src/ui.mjs").toString("utf8"))) : read(`src/${f}`));
  }
  const core = "vendor/atep-core";
  for (const f of ["index.js", "THIRD-PARTY-NOTICES.md"]) files.set(`${core}/${f}`, read(`${core}/${f}`));
  for (const f of fs.readdirSync(path.join(src, core, "wasm")).filter((n) => /\.(js|wasm)$/.test(n)).sort()) files.set(`${core}/wasm/${f}`, read(`${core}/wasm/${f}`));
  return files;
}

function listOut(dir, base = "") {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? listOut(path.join(dir, e.name), base + e.name + "/") : [base + e.name]));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const files = buildFiles();
  if (process.argv.includes("--check")) {
    const problems = [];
    for (const [rel, buf] of files) {
      const p = path.join(out, rel);
      if (!fs.existsSync(p)) problems.push(`missing ${rel}`);
      else if (!fs.readFileSync(p).equals(buf)) problems.push(`stale ${rel}`);
    }
    for (const rel of listOut(out)) if (!files.has(rel)) problems.push(`unexpected ${rel}`);
    if (problems.length) {
      console.error(`FAIL atep.dev/demo/ is out of date: ${problems.join(", ")}\nrun: node site/build-demo.mjs`);
      process.exit(1);
    }
    console.log(`demo copy up to date: ${files.size} files`);
  } else {
    fs.rmSync(out, { recursive: true, force: true });
    for (const [rel, buf] of files) {
      const p = path.join(out, rel);
      fs.mkdirSync(path.dirname(p), { recursive: true });
      fs.writeFileSync(p, buf);
    }
    console.log(`wrote atep.dev/demo/ (${files.size} files)`);
  }
}
